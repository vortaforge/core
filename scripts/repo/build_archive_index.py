#!/usr/bin/env python3
"""Generate the mod's compact copy of the archive registry.

The mod needs to answer one question about a pack - "is this one of ours that we
retired?" - and the real answer lives in ``archived/archive.json``, which has 32
projects and nineteen fields each. Shipping that would put a second, staler copy
of the registry in a jar.

So this writes the three fields the mod actually reads: id, content hash and a
one-line reason. The hash is computed here, from the pack on disk, with the same
framing ``ContentHash.java`` uses - path length, path, content length, content,
in sorted path order - so a hash produced by this script matches one produced by
the mod. ``tools/test_scan_parity.py`` asserts that.

Usage:  python3 scripts/repo/build_archive_index.py [--check]
Exit:   0 written or already current, 1 when --check found a stale file.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "archived" / "archive.json"
TARGET = ROOT / "mods" / "macroengine" / "src" / "main" / "resources" / "assets" / "macroengine" / "archive-index.json"
KINDS = ("datapack", "resourcepack")


def content_hash(root: pathlib.Path) -> str:
    """Mirror of ContentHash.ofDirectory: sorted paths, length-prefixed framing."""
    files = sorted(
        (p for p in root.rglob("*") if p.is_file()),
        key=lambda p: p.relative_to(root).as_posix(),
    )
    digest = hashlib.sha256()
    for path in files:
        rel = path.relative_to(root).as_posix().encode("utf-8")
        data = path.read_bytes()
        digest.update(len(rel).to_bytes(4, "big"))
        digest.update(rel)
        digest.update(len(data).to_bytes(4, "big"))
        digest.update(data)
    return digest.hexdigest()


def build() -> dict:
    projects = json.loads(REGISTRY.read_text(encoding="utf-8"))["projects"]
    out = []
    for project in projects:
        if project.get("kind") not in KINDS or not project.get("path"):
            continue
        root = ROOT / project["path"]
        if not root.is_dir():
            print(f"skipped {project['id']}: {project['path']} is not a directory", file=sys.stderr)
            continue
        reason = (project.get("reason") or "").strip().split(".")[0]
        out.append({
            "id": project["id"],
            "hash": content_hash(root),
            "reason": reason[:160],
        })
    return {
        "schemaVersion": 1,
        "generatedFrom": "archived/archive.json",
        "note": "Generated by scripts/repo/build_archive_index.py. Do not edit by hand.",
        "projects": out,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the committed copy is stale")
    args = parser.parse_args()

    built = build()
    text = json.dumps(built, indent=2) + "\n"

    if args.check:
        if not TARGET.is_file():
            print(f"{TARGET.relative_to(ROOT)} is missing", file=sys.stderr)
            return 1
        if TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET.relative_to(ROOT)} is stale; run this script without --check",
                  file=sys.stderr)
            return 1
        print(f"ok: {len(built['projects'])} archived pack(s) match the registry")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(built['projects'])} pack(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
