"""Java Edition output: one combined datapack (+ optional companion resource pack)."""
from __future__ import annotations
import json, os
from pathlib import Path
from . import attribution
from .fileset import FileSet
from .index import PackIndex
from .paths import ME_DP, ME_RP, GUI_DP, ME_NS, GUI_NS
from .rename import Renamer, build_rules
from .schema import config_schema, snbt_value

TEXT_EXT = (".mcfunction", ".json", ".mcmeta", ".md", ".svg", ".txt")
MERGE_TAGS = ("data/minecraft/tags/function/load.json", "data/minecraft/tags/function/tick.json")


class BuildError(Exception):
    pass


def _walk(root: Path):
    for dp, _, fs in os.walk(root):
        for f in sorted(fs):
            p = Path(dp) / f
            yield p, p.relative_to(root).as_posix()


def _res_for_path(rel: str):
    """data/<ns>/<...> -> (kind,id) using the same rules as PackIndex."""
    from .index import _kind_and_id
    parts = rel.split("/")
    if parts[0] != "data" or len(parts) < 3:
        return None
    return _kind_and_id(parts[1], parts[2:])


def _stamp(cfg, rel, text):
    if rel.endswith(".mcfunction"):
        return f"# {cfg.name}: code from macroEngine/guikit (Unlicense), renamed by packweld. See NOTICE.md\n" + text
    return text


def _pack_mcmeta(desc, lo, hi):
    return json.dumps({"pack": {"description": desc, "min_format": lo, "max_format": hi}}, indent=2) + "\n"


def build_datapack(cfg) -> tuple:
    """Return (FileSet, info dict)."""
    fs = FileSet()
    info = {"kept_modules": None, "pulled": {}, "functions": 0, "renames": 0}
    me, gui = cfg.include_macroengine, cfg.include_guikit
    rn = Renamer(build_rules(cfg, macroengine=me, guikit=gui))
    tags = {p: [] for p in MERGE_TAGS}

    def add_tree(root: Path, keep=None):
        for p, rel in _walk(root):
            if not rel.startswith("data/"):
                continue
            if keep is not None:
                r = _res_for_path(rel)
                if r is not None and r not in keep:
                    continue
            raw = p.read_bytes()
            new_rel = rn.path(rel)
            if rel in MERGE_TAGS:
                tags[rel].extend(json.loads(rn.text(raw.decode("utf-8")))["values"])
                continue
            if rel.endswith(TEXT_EXT):
                try:
                    txt = rn.text(raw.decode("utf-8"))
                except UnicodeDecodeError:
                    fs.put(new_rel, raw); continue
                if cfg.stamp_headers:
                    txt = _stamp(cfg, new_rel, txt)
                fs.put(new_rel, txt)
            else:
                fs.put(new_rel, raw)

    keep = None
    if me:
        ix = PackIndex(ME_DP, ME_NS)
        extra = []
        if cfg.config_overrides:
            extra.append(("function", f"{ME_NS}:core/config/set"))
        if cfg.modules is not None:
            keep, pulled = ix.select(cfg.modules, extra)
            info["kept_modules"] = sorted(cfg.modules)
            info["pulled"] = pulled
        add_tree(ME_DP, keep)
    if gui:
        add_tree(GUI_DP)

    # generated: config overrides (runs after setup, goes through the validated core/config/set)
    if me and cfg.config_overrides:
        schema = config_schema()
        lines = [f"# {cfg.namespace}:generated/apply_config — written by packweld from config_overrides"]
        for k, v in cfg.config_overrides.items():
            try:
                sv = snbt_value(k, v, schema)
            except (KeyError, ValueError) as e:
                raise BuildError(f"config override: {e}")
            lines.append(f'data modify storage {cfg.namespace}:engine config_in set value {{key:"{k}",value:{sv}}}')
            lines.append(f"function {cfg.namespace}:core/config/set")
        fs.put(f"data/{cfg.namespace}/function/generated/apply_config.mcfunction", "\n".join(lines) + "\n")
        tags[MERGE_TAGS[0]].append(f"{cfg.namespace}:generated/apply_config")

    for path, vals in tags.items():
        if vals:
            fs.put(path, json.dumps({"values": vals}, indent=2) + "\n")

    # metadata
    desc = cfg.description or f"{cfg.name} v{cfg.version} (macroEngine/guikit library, generated by packweld)"
    fs.put("pack.mcmeta", _pack_mcmeta(desc, cfg.min_format, cfg.max_format))
    icon = Path(cfg.icon).read_bytes() if cfg.icon else (ME_DP / "pack.png").read_bytes()
    fs.put("pack.png", icon)
    fs.put("LICENSE", (ME_DP / "LICENSE").read_text(encoding="utf-8"))
    fs.put("NOTICE.md", attribution.notice(cfg, macroengine=me, guikit=gui, bedrock="bedrock" in cfg.targets))
    for p, t in attribution.licence_files(macroengine=me, guikit=gui, rp=me and cfg.include_resourcepack).items():
        fs.put(p, t)
    fs.put("README.md", attribution.readme(cfg, macroengine=me, guikit=gui, kept_modules=info["kept_modules"], bedrock="bedrock" in cfg.targets))
    if me and cfg.include_docs:
        for p, rel in _walk(ME_DP / "docs"):
            data = p.read_bytes()
            fs.put(f"docs/{rel}", data)   # upstream docs kept verbatim (original names), see README

    info["functions"] = sum(1 for k in fs if k.endswith(".mcfunction"))
    info["renames"] = rn.count
    return fs, info


def build_resourcepack(cfg) -> FileSet:
    fs = FileSet()
    rn = Renamer({**build_rules(cfg, macroengine=True, guikit=False)})
    for p, rel in _walk(ME_RP):
        if rel in ("pack.mcmeta", "LICENSE"):
            continue
        raw = p.read_bytes()
        new_rel = rn.path(rel)
        if rel.endswith(TEXT_EXT):
            fs.put(new_rel, rn.text(raw.decode("utf-8")))
        else:
            fs.put(new_rel, raw)
    desc = f"{cfg.name} — resource pack (i18n, sounds, trim assets) generated by packweld"
    fs.put("pack.mcmeta", json.dumps({"pack": {"description": desc, "min_format": cfg.rp_min_format,
                                               "max_format": cfg.rp_max_format},
                                      "features": {"enabled": ["minecraft:vanilla"]}}, indent=2) + "\n")
    icon = Path(cfg.icon).read_bytes() if cfg.icon else (ME_RP / "pack.png").read_bytes()
    fs.put("pack.png", icon)
    fs.put("LICENSE", (ME_RP / "LICENSE").read_text(encoding="utf-8"))
    fs.put("NOTICE.md", attribution.notice(cfg, macroengine=True, guikit=False))
    return fs
