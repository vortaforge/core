def read(p):
    return p.read_text(encoding="utf-8")


def notice(cfg, *, macroengine: bool, guikit: bool, bedrock: bool = False) -> str:
    L = [f"# NOTICE — {cfg.name}", "",
         f"**{cfg.name}** v{cfg.version} was generated with *packweld* v{__version__} from upstream Minecraft pack code.",
         "The upstream code is reproduced as-is; only the namespace, scoreboard/tag/storage names, display names and",
         "pack metadata were rewritten. No gameplay logic was edited.", "", "## Upstream sources", ""]
    if macroengine:
        L += ["- **macroEngine** (datapack + resource pack) v26.3 — Unlicense (public domain).",
              "  Maintained by VortaForge (https://github.com/vortaforge, repo `vortaforge/core`);",
              "  former owner Runtoolkit (archived). Original namespace: `macroengine`.",
              "  Licence: `licenses/macroEngine-LICENSE.txt`."]
    if guikit:
        L += ["- **guikit** datapack — Unlicense (public domain). Original namespace: `guikit`.",
              "  Licence: `licenses/guikit-LICENSE.txt`."]
    if macroengine:
        L += ["", "## Third-party code (MIT)", "",
              "macroEngine's own notice lists **PlayerAction** by Michael Weatherby (https://github.com/ICY105/PlayerAction, MIT).",
              "Upstream describes it as a dependency scheduled for removal, and the click-detection code under",
              "`core/internal/player/` still uses its `player_action.*` identifiers, so the MIT notice is kept:",
              "see `licenses/THIRD_PARTY_LICENSES.md`. It must stay with every copy of this pack."]
        if cfg.isolate_player_action:
            L += ["Those identifiers were renamed to `%s_pa.*` (option isolate_player_action) so two generated packs do not collide." % cfg.namespace]
    L += ["", "## What the generator changed", "",
          f"- namespace `macroengine` -> `{cfg.namespace}`" if macroengine else "",
          f"- namespace `guikit` -> `{cfg.gui_ns}`" if guikit else "",
          "- scoreboard objectives, tags, storage ids, NBT keys and file names containing those names",
          "- display strings (\"MacroEngine\", \"macroEngine\", ...) -> \"%s\"" % cfg.name if macroengine else "",
          "- `pack.mcmeta`, README, this NOTICE and the licence copies were generated",
          ]
    if cfg.modules is not None and macroengine:
        L.append(f"- macroEngine was trimmed to {len(cfg.modules)} selected modules plus everything they statically reference")
    if cfg.config_overrides and macroengine:
        L.append(f"- runtime config overrides applied at load by `{cfg.namespace}:generated/apply_config`")
    if bedrock:
        L += ["", "## Bedrock add-on", "",
              "The Bedrock add-on is **not** a conversion of the Java datapack: Bedrock has no data storage, macros,",
              "or item components. It is a separate JavaScript (Script API) re-implementation of a portable subset,",
              "written for packweld (AI-assisted, see CREDITS.md in the generator repository)."]
    if cfg.author:
        L += ["", f"Generated for: {cfg.author}" + (f" — {cfg.homepage}" if cfg.homepage else "")]
    if cfg.extra_notice:
        L += ["", "## Additional notice", "", cfg.extra_notice]
    return "\n".join(l for l in L if l is not None) + "\n"


def licence_files(*, macroengine: bool, guikit: bool, rp: bool) -> dict:
    out = {}
    if macroengine:
        out["licenses/macroEngine-LICENSE.txt"] = read(ME_DP / "LICENSE")
        out["licenses/THIRD_PARTY_LICENSES.md"] = read(ME_DP / "THIRD_PARTY_LICENSES.md")
        out["licenses/macroEngine-UPSTREAM-README.md"] = read(ME_DP / "README.md")
    if guikit:
        out["licenses/guikit-LICENSE.txt"] = read(GUI_DP / "LICENSE")
        out["licenses/guikit-UPSTREAM-README.md"] = read(GUI_DP / "README.md")
    if rp:
        out["licenses/macroEngine-resourcepack-LICENSE.txt"] = read(ME_RP / "LICENSE")
    return out


def readme(cfg, *, macroengine: bool, guikit: bool, kept_modules, bedrock: bool) -> str:
    X, Y = cfg.namespace, cfg.gui_ns
    L = [f"# {cfg.name} v{cfg.version}", "", cfg.description or "Self-contained library datapack generated by packweld.", "",
         "No external library or dependency is needed: everything lives in this pack under its own namespace.", ""]
    if macroengine:
        L += [f"## Library (`{X}:`)", "", "Call public functions from your own pack, for example:", "",
              "```mcfunction", f"function {X}:api/perm/grant", f"function {X}:api/cb/run_delayed", "```", "",
              f"Entry points live under `{X}:api/`, `{X}:systems/` and `{X}:input/`. Upstream docs are in `docs/`",
              f"(they still show the original `macroengine:` names: replace it with `{X}:`).", ""]
        if kept_modules is not None:
            L += ["Included modules: " + ", ".join(f"`{m}`" for m in kept_modules), ""]
        L += ["The upstream resource pack (text, sounds) must be installed with the datapack." if cfg.include_resourcepack else "", ""]
    if guikit:
        L += [f"## GUI editor (`{Y}:`)", "", f"`/trigger {Y}.open` opens published menus; operators use `/function {Y}:editor/open`.", ""]
    L += ["## Credits and licences", "", "See `NOTICE.md` and `licenses/`. Upstream: macroEngine, guikit (Unlicense); PlayerAction (MIT).", "",
          "Minecraft target: Java 26.3 only (pack format %s). Not verified in a live client by the generator." % ".".join(map(str, cfg.min_format)), ""]
    return "\n".join(L)
