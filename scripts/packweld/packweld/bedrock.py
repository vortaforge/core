"""Bedrock add-on output (.mcaddon = behavior pack + resource pack).

This is a re-implementation of a portable subset in the Script API, NOT a transpile of the Java
datapacks (Bedrock has no data storage, macros or item components).
"""
from __future__ import annotations
import json, re, uuid
from pathlib import Path
from . import attribution
from .fileset import FileSet
from .paths import ROOT, ME_DP, GUI_DP, ME_RP

JS_DIR = ROOT / "bedrock_js"
MODULES = {
    "store": "World / per-player key-value store (dynamic properties): set, get, add, toggle, append, list",
    "math": "clamp, lerp, map_range, gcd/lcm, sin/cos (deg), vector ops",
    "string": "pad, truncate, title_case, pluralize, format_coords, progress_bar",
    "rng": "Seedable deterministic RNG: seed, next, int, chance, pick, weighted",
    "perm": "Tag based permissions: grant, revoke, has, check, list, clear",
    "rate_limit": "Per-key / per-player rate limits",
    "toggle": "Switch other modules on/off at runtime",
    "cb": "Callback queue: run, run_delayed, run_sequence, cancel",
    "hook": "Bind commands/JS callbacks to game events",
    "title": "Title / action bar with {player} {x} {y} {z} {score:obj} {store:key} tokens",
    "gui": "guikit-style menus as forms (ActionFormData), opened by scriptevent or item",
}
ACTIONS = {"close", "message", "open", "sound", "command", "give", "toggle", "counter"}
ITEM = re.compile(r"^[a-z0-9_.]+:[a-z0-9_./]+$")
MENU_ID = re.compile(r"^[a-z0-9_]{1,32}$")


class BedrockError(Exception):
    pass


def _validate_menus(menus):
    ids = set()
    for m in menus:
        if not MENU_ID.match(str(m.get("id", ""))):
            raise BedrockError(f"menu id must match [a-z0-9_]: {m.get('id')!r}")
        if m["id"] in ids:
            raise BedrockError(f"duplicate menu id {m['id']}")
        ids.add(m["id"])
        if not m.get("buttons"):
            raise BedrockError(f"menu {m['id']} needs at least one button")
        for b in m["buttons"]:
            if "text" not in b:
                raise BedrockError(f"menu {m['id']}: button without text")
            a = b.get("action", {"type": "close"})
            if a.get("type") not in ACTIONS:
                raise BedrockError(f"menu {m['id']}: unknown action {a.get('type')!r} (allowed: {sorted(ACTIONS)})")
            if a["type"] == "give" and not ITEM.match(str(a.get("item", ""))):
                raise BedrockError(f"menu {m['id']}: bad item id {a.get('item')!r}")
    for m in menus:
        for b in m["buttons"]:
            a = b.get("action", {})
            if a.get("type") == "open" and a.get("menu") not in ids:
                raise BedrockError(f"menu {m['id']}: opens unknown menu {a.get('menu')!r}")


def _uid(ns, what, ver):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"packweld:{ns}:{what}:{ver}"))


def build_bedrock(cfg) -> dict:
    """Return {'bp': FileSet, 'rp': FileSet, 'info': {...}}."""
    b = cfg.bedrock
    ns = cfg.bedrock_ns
    mods = list(MODULES) if b.modules is None else list(b.modules)
    unknown = [m for m in mods if m not in MODULES]
    if unknown:
        raise BedrockError(f"unknown bedrock modules {unknown}; available: {list(MODULES)}")
    menus = b.menus or [{"id": "welcome", "title": cfg.name, "body": "Welcome!",
                         "buttons": [{"text": "Close", "action": {"type": "close"}}]}]
    _validate_menus(menus)
    default_menu = b.gui_default_menu or menus[0]["id"]
    if default_menu not in {m["id"] for m in menus}:
        raise BedrockError(f"gui_default_menu {default_menu!r} not in menus")
    ver = [int(x) for x in cfg.version.split(".")]
    bp_id, rp_id = _uid(ns, "bp", cfg.version), _uid(ns, "rp", cfg.version)
    bp_mod, bp_script = _uid(ns, "bp-data", cfg.version), _uid(ns, "bp-script", cfg.version)

    bp, rp = FileSet(), FileSet()
    # scripts
    order = ["core"] + [m for m in MODULES if m in mods and m != "gui"] + (["gui", "menus"] if "gui" in mods else [])
    imports = []
    for m in order:
        if m == "menus":
            bp.put("scripts/menus.js",
                   "// generated by packweld from the menus in the build config\n"
                   f"export const MENUS = {json.dumps(menus, indent=2, ensure_ascii=False)};\n"
                   f"export const OPEN_ITEM = {json.dumps(b.gui_open_item)};\n"
                   f"export const DEFAULT_MENU = {json.dumps(default_menu)};\n")
            continue
        src = (JS_DIR / f"{m}.js").read_text(encoding="utf-8").replace("__NS__", ns)
        bp.put(f"scripts/{m}.js", src)
        if m != "core":
            imports.append(f'import "./{m}.js";')
    bp.put("scripts/main.js",
           "// generated by packweld — loads the selected modules\n" + "\n".join(imports) +
           f'\nimport {{ api }} from "./core.js";\nglobalThis.{ns}_api = api;   // for other scripts in the same world\n')
    # manifest
    deps = [{"module_name": "@minecraft/server", "version": b.server_version}]
    if "gui" in mods:
        deps.append({"module_name": "@minecraft/server-ui", "version": b.server_ui_version})
    deps.append({"uuid": rp_id, "version": ver})
    bp.put("manifest.json", json.dumps({
        "format_version": 2,
        "header": {"name": f"{cfg.name} BP", "description": cfg.description or f"{cfg.name} behavior pack (packweld)",
                   "uuid": bp_id, "version": ver, "min_engine_version": b.min_engine_version},
        "modules": [{"type": "data", "uuid": bp_mod, "version": ver},
                    {"type": "script", "language": "javascript", "uuid": bp_script, "version": ver, "entry": "scripts/main.js"}],
        "dependencies": deps}, indent=2) + "\n")
    # functions (command-block friendly wrappers over scriptevent)
    raw = lambda t: json.dumps({"rawtext": [{"text": t}]}, ensure_ascii=False)
    help_lines = [f"tellraw @s {raw(f'[{cfg.name}] call modules with: /scriptevent {ns}:<module>.<function> <json>')}",
                  f"tellraw @s {raw('modules: ' + ', '.join(mods))}"]
    bp.put(f"functions/{ns}/help.mcfunction", "\n".join(help_lines) + "\n")
    if "gui" in mods:
        bp.put(f"functions/{ns}/gui/open.mcfunction", f'scriptevent {ns}:gui.open {{"menu":"{default_menu}"}}\n')
    # resource pack
    rp.put("manifest.json", json.dumps({
        "format_version": 2,
        "header": {"name": f"{cfg.name} RP", "description": f"{cfg.name} resource pack (packweld)",
                   "uuid": rp_id, "version": ver, "min_engine_version": b.min_engine_version},
        "modules": [{"type": "resources", "uuid": _uid(ns, "rp-res", cfg.version), "version": ver}]}, indent=2) + "\n")
    rp.put("texts/languages.json", json.dumps(["en_US"]) + "\n")
    rp.put("texts/en_US.lang", f"pack.name={cfg.name}\npack.description={cfg.description or cfg.name}\n")
    icon = Path(cfg.icon).read_bytes() if cfg.icon else (ME_DP / "pack.png").read_bytes()
    for fs in (bp, rp):
        fs.put("pack_icon.png", icon)
        fs.put("NOTICE.md", attribution.notice(cfg, macroengine=cfg.include_macroengine, guikit=cfg.include_guikit, bedrock=True))
        fs.put("LICENSE", (ME_DP / "LICENSE").read_text(encoding="utf-8"))
        for p, t in attribution.licence_files(macroengine=cfg.include_macroengine, guikit=cfg.include_guikit, rp=False).items():
            fs.put(p, t)
    return {"bp": bp, "rp": rp, "info": {"modules": mods, "menus": [m["id"] for m in menus], "namespace": ns}}


def mcaddon(cfg, parts) -> bytes:
    fs = FileSet()
    for p, d in parts["bp"].items():
        fs.put(f"{cfg.name} BP/{p}", d)
    for p, d in parts["rp"].items():
        fs.put(f"{cfg.name} RP/{p}", d)
    return fs.zip_bytes()
